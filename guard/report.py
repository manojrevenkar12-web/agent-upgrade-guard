"""Generated reports: reports/results.json (everything measured), reports/REPORT.md (the same, for
reading) and web/public/data.json (what the dashboard shows). Never edit them by hand: run `guard report`."""

from __future__ import annotations

import hashlib
import json

from guard.compare import load_config
from guard.evaluate import ROOT, budget_sweep, load_bench, run, score
from guard.spec import unread

HELDOUT = ROOT / "eval" / "heldout"


def world_digest(spec: dict, bench: dict) -> str:
    from guard.evaluate import world

    agents, truths = world(spec)
    blob = json.dumps({"agents": [a.to_dict() for a in agents], "truth": [t.to_dict() for t in truths]}, sort_keys=True, ensure_ascii=False)
    return hashlib.sha256(blob.encode()).hexdigest()


def _agent_card(rep, truth=None) -> dict:
    d = rep.to_dict()
    d["obligations"] = [
        {
            "kind": o["obligation"]["kind"],
            "source": o["obligation"]["source"],
            "implicit": o["obligation"]["implicit"],
            "params": o["obligation"]["params"],
            "hard": o["hard"],
            "state": o["state"],
            "p": round(o["p_value"], 4),
            "slice": o["stratum"],
            "baseline": [o["baseline_fail"], o["baseline_n"]],
            "candidate": [o["candidate_fail"], o["candidate_n"]],
            "examples": o["examples"],
        }
        for o in d["obligations"]
    ]
    return d


def build_results(with_sweep: bool = True) -> dict:
    cfg = load_config()
    bench = load_bench()
    dev = run(bench["dev"], bench, cfg)
    s = score(dev["rows"], cfg["text_diff_threshold"])
    cards = []
    for rep, a in zip(dev["reports"], dev["agents"], strict=True):
        c = _agent_card(rep)
        c["domain"] = next(r["domain"] for r in dev["rows"] if r["agent_id"] == a.id)
        c["instructions"] = a.instructions
        c["knowledge_docs"] = [d.title for d in a.knowledge]
        c["tools"] = [t.name for t in a.tools]
        c["consumer"] = a.consumer
        c["unread"] = unread(a)
        cards.append(c)
    out = {
        "generated_by": "guard report",
        "config": {k: v for k, v in cfg.items() if not k.startswith("_")},
        "dev": {"score": s, "mining": {k: v for k, v in dev["mining"].items() if k != "misses"}, "seconds": dev["seconds"]},
        "budget": budget_sweep(bench["dev"], bench, cfg, [4, 6, 8, 12, 16]) if with_sweep else [],
        "agents": cards,
        "heldout": {},
    }
    for v in ("v1", "v2"):
        first = HELDOUT / v / "first_run.json"
        if first.exists():
            h = json.loads(first.read_text())
            h.pop("rows", None)
            h["set"] = v
            out["heldout"][v] = h
    return out


def pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def markdown(res: dict) -> str:
    s = res["dev"]["score"]
    g, t, c = s["guard"], s["text_diff"], s["cost"]
    lines = [
        "# Results",
        "",
        "Generated by `guard report`. Do not edit by hand.",
        "",
        f"Development workspace: {s['agents']} simulated agents, {s['regressed_agents']} of them with a planted regression in the candidate model, "
        f"{s['clean_agents']} without (many of those with harmless changes such as new wording).",
        "",
        "| | Upgrade guard | Text-diff gate (best dev threshold) |",
        "|---|---|---|",
        f"| Regressed agents caught | {pct(g['recall'])} | {pct(t['recall'])} |",
        f"| Clean agents wrongly flagged | {pct(g['false_alarm_rate'])} | {pct(t['false_alarm_rate'])} |",
        f"| Clean agents with new wording wrongly flagged | {pct(g['false_alarms_on_reworded'])} | {pct(t['false_alarms_on_reworded'])} |",
        f"| Broken obligations named | {pct(g['obligation_recall'])} | n/a (no reason given) |",
        "",
        f"Hard regressions (language, JSON, actions, refusals, scope, asking back) blocked: {pct(g['hard_blocked'])}; the rest were sent to review.",
        f"Cost: {c['probes_per_agent']} test messages and about {c['tokens_per_agent']:,} tokens per agent and model.",
        "",
        "## Caught by how often the regression shows",
        "",
        "| Share of answers affected | Agents | Guard | Text diff |",
        "|---|---|---|---|",
    ]
    for k, v in s["recall_by_strength"].items():
        lines.append(f"| {k} | {v['agents']} | {pct(v['guard'])} | {pct(v['text_diff'])} |")
    lines += [
        "",
        "## Obligations read from instructions (dev phrasing)",
        "",
        f"Precision {pct(res['dev']['mining']['precision'])}, recall {pct(res['dev']['mining']['recall'])}.",
        "",
        "| Kind | Found | Invented | Missed | Wrong parameters |",
        "|---|---|---|---|---|",
    ]
    for k, v in res["dev"]["mining"]["per_kind"].items():
        lines.append(f"| {k} | {v['tp']} | {v['fp']} | {v['fn']} | {v['wrong_params']} |")
    if g["missed_by_kind"]:
        lines += [
            "",
            "## Missed regressions on dev",
            "",
            "| Obligation | Not read | Not tested | Tested, not significant |",
            "|---|---|---|---|",
        ]
        for k, v in g["missed_by_kind"].items():
            lines.append(f"| {k} | {v['not mined']} | {v['untested']} | {v['held']} |")
    if res["budget"]:
        lines += [
            "",
            "## Test messages per kind (dev)",
            "",
            "| Per kind | Messages per agent | Tokens per agent | Caught | Wrongly flagged |",
            "|---|---|---|---|---|",
        ]
        for b in res["budget"]:
            lines.append(
                f"| {b['per_kind']} | {b['probes_per_agent']} | {b['tokens_per_agent']:,} | {pct(b['recall'])} | {pct(b['false_alarm_rate'])} |"
            )
    notes = {
        "v1": "Held-out phrasing written with the dev phrasing, before the first run. This is the result for the first version.",
        "v2": "Written after the v1 run, before the fixes that v1 prompted were tested on it; run once after those fixes. "
        "It is the result for the current version.",
    }
    for v, h in (res.get("heldout") or {}).items():
        hs = h["score"]
        lines += [
            "",
            f"## Held-out workspace {v}",
            "",
            notes[v],
            "",
            f"Run once on {h['run_at']}, on {hs['agents']} agents pinned before the run (sha256 `{h['world_sha256'][:16]}…`).",
            "",
            "| | Upgrade guard | Text-diff gate (dev threshold) |",
            "|---|---|---|",
            f"| Regressed agents caught | {pct(hs['guard']['recall'])} | {pct(hs['text_diff']['recall'])} |",
            f"| Clean agents wrongly flagged | {pct(hs['guard']['false_alarm_rate'])} | {pct(hs['text_diff']['false_alarm_rate'])} |",
            f"| Broken obligations named | {pct(hs['guard']['obligation_recall'])} | n/a |",
            f"| Obligations read from instructions | precision {pct(h['mining']['precision'])}, recall {pct(h['mining']['recall'])} | |",
        ]
        if hs["guard"]["missed_by_kind"]:
            lines += ["", "| Missed obligation | Not read | Not tested | Tested, not significant |", "|---|---|---|---|"]
            for k, m in hs["guard"]["missed_by_kind"].items():
                lines.append(f"| {k} | {m['not mined']} | {m['untested']} | {m['held']} |")
    if not res.get("heldout"):
        lines += ["", "## Held-out workspaces", "", "Not run yet."]
    return "\n".join(lines) + "\n"


def write_all(res: dict) -> None:
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "reports" / "results.json").write_text(json.dumps(res, indent=1, ensure_ascii=False) + "\n")
    (ROOT / "reports" / "REPORT.md").write_text(markdown(res))
    web = ROOT / "web" / "public"
    web.mkdir(parents=True, exist_ok=True)
    (web / "data.json").write_text(json.dumps(res, ensure_ascii=False))
